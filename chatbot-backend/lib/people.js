/**
 * people.js
 * ---------
 * Everything the chatbot needs to talk about *people* accurately:
 *
 *  - personCard(member):   one uniform contact card (name, role, location,
 *                          credentials, expertise, email, View Profile / Connect)
 *  - answerPersonQuery():  "who is disha", "email of tasnim", "dhisa shah" ...
 *                          (fuzzy name match — typos, first name only, etc.)
 *  - answerSectorExpertsQuery(): "who are the experts in media", "IT/ITES",
 *                          "ngo specialist" ... answered from the specialists
 *                          the website itself lists on each sector page.
 *  - peopleNamedIn(text):  every team member named in a piece of text, so an
 *                          AI-written answer can get real cards under it.
 *
 * All of it is computed from index.json + data/contacts.json in code, so
 * names, roles, locations and emails are exactly what the website shows —
 * nothing here is generated by the LLM.
 */
const fs = require("fs");
const path = require("path");

// Used when the website lists no personal email for someone — clearly labelled
// as the firm's general address in the card, never passed off as theirs.
const GENERAL_EMAIL = "connect@jhsassociates.in";

// ---- small helpers -------------------------------------------------------

// Edit distance where swapping two neighbouring letters counts as ONE typo
// ("dhisa" -> "disha"), which is by far the most common way people mistype.
function distance(a, b) {
  const dp = Array.from({ length: a.length + 1 }, () => Array(b.length + 1).fill(0));
  for (let i = 0; i <= a.length; i++) dp[i][0] = i;
  for (let j = 0; j <= b.length; j++) dp[0][j] = j;
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + cost);
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) {
        dp[i][j] = Math.min(dp[i][j], dp[i - 2][j - 2] + 1);
      }
    }
  }
  return dp[a.length][b.length];
}

const norm = (s) => String(s || "").toLowerCase().replace(/[^a-z]/g, "");
const words = (s) => String(s || "").toLowerCase().match(/[a-z]+/g) || [];
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// How many typos a name-part of this length may have and still count as a match.
function tolerance(len) {
  if (len >= 8) return 2;
  if (len >= 5) return 1;
  return 0;
}
function tokenMatches(q, n) {
  if (q === n) return true;
  if (q.length < 4) return false; // 3-letter words are too easy to match by accident
  if (distance(q, n) <= Math.min(tolerance(n.length), tolerance(q.length))) return true;
  // Same letters scrambled, same first letter ("dhisa" for "disha") — a very
  // common way to mistype a name that a plain edit distance scores as 2 typos.
  return q.length >= 5 && q.length === n.length && q[0] === n[0] && [...q].sort().join("") === [...n].sort().join("");
}
// Looser than tokenMatches (up to 2 typos): only used to rank people who ALREADY
// matched on another part of their name, e.g. "dhisa shah" -> Disha over the
// other five Shahs.
function softMatches(q, n) {
  return q.length >= 4 && n.length >= 4 && distance(q, n) <= 2;
}

// ---- contacts (email / LinkedIn), from data/contacts.json ----------------

function loadContacts() {
  const merged = {};
  for (const file of ["contacts.json", "contacts.overrides.json"]) {
    const p = path.join(__dirname, "..", "data", file);
    if (!fs.existsSync(p)) continue;
    try {
      const data = JSON.parse(fs.readFileSync(p, "utf-8"));
      for (const [name, c] of Object.entries(data)) merged[name] = { ...merged[name], ...c };
    } catch (e) {
      console.warn(`Could not read ${file}:`, e.message);
    }
  }
  return merged;
}

// The same person is often spelled slightly differently across the website
// ("Narayan" / "Narayana" Rao Malla) and one spelling may carry the email while
// another only has the LinkedIn — so merge every entry that is this person,
// closest spelling first, filling in whatever the closer ones are missing.
function contactFor(contacts, name) {
  const target = norm(name);
  const matches = [];
  for (const [key, c] of Object.entries(contacts)) {
    const d = key === name ? 0 : distance(norm(key), target);
    if (d === 0 || (d <= 2 && target.length >= 8)) matches.push({ d, c });
  }
  matches.sort((x, y) => x.d - y.d);
  const merged = {};
  for (const { c } of matches) for (const [k, v] of Object.entries(c)) if (v && !merged[k]) merged[k] = v;
  return merged;
}

