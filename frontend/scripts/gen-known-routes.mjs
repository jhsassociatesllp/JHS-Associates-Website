// Builds an nginx "map" of every page the app really has, so the server can answer unknown URLs
// with HTTP 404 instead of 200 (audit HDR-01). Run after `vite build`; writes known-routes.inc next to package.json (kept out of dist/ so it is never served).
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(new URL('../src/App.tsx', import.meta.url), 'utf8')
const paths = new Set(['/'])
for (const m of src.matchAll(/<Route\s+path="([^"]+)"/g)) {
  if (m[1] !== '*') paths.add(m[1])
}

// characters that mean something in a regular expression
const SPECIAL = /[.*+?^${}()|[\]\\]/g
const esc = (s) => s.replace(SPECIAL, (c) => '\\' + c)

const lines = [...paths]
  .sort()
  .map((p) => {
    const pattern = p
      .split('/')
      .map((seg) => (seg.startsWith(':') ? '[^/]+' : esc(seg)))
      .join('/')
    return `    "~*^${pattern}/?$" 1;`
  })

const conf = `# generated by scripts/gen-known-routes.mjs - do not edit
map $uri $jhs_known_route {
    default 0;
${lines.join('\n')}
}
`
writeFileSync(new URL('../known-routes.inc', import.meta.url), conf)
console.log(`known-routes.inc: ${paths.size} routes`)
